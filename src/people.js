const pick = (a, i) => a[i % a.length];

function makePerson(archId, seed, forceSex) {
  const A = ARCHETYPES.find((x) => x.id === archId) || ARCHETYPES[0];
  const sex = forceSex || A.sex || (seed % 2 === 0 ? "m" : "f");
  const pool = sex === "f" ? NAMES_F : NAMES_M;
  return {
    id: archId + "_" + seed,
    seed,
    name: pick(A.title, seed) + pick(pool, seed * 7 + 3),
    arch: archId,
    sex,
    color: pick(TRIMS, seed * 5 + 1),
    hair: pick(HAIRS, seed * 3 + 2),
    style: A.style || "uniform",
    blazer: (A.wear && A.wear.blazer) !== undefined ? A.wear.blazer : pick(BLAZERS, seed * 11 + 4),
    pants: A.wear && A.wear.pants,
    shoes: A.wear && A.wear.shoes,
    trim: (A.wear && A.wear.trim) !== undefined ? A.wear.trim : pick(TRIMS, seed * 5 + 1),
    skirt: sex === "f" ? pick(SKIRTS, seed * 13) : undefined,
    acc: pick(A.acc || ["none"], seed * 17),
    courage: Math.round(A.courage * (0.82 + ((seed * 37) % 40) / 100)),
    speed: +(A.speed * (0.9 + ((seed * 23) % 25) / 100)).toFixed(2),
    idle: A.idle, scared: A.scared, flee: A.flee,
  };
}

function namedToType(n) {
  const A = ARCHETYPES.find((x) => x.id === n.arch) || ARCHETYPES[0];
  const W = A.wear || {};
  return {
    id: "named_" + n.name, name: n.name, arch: n.arch, sex: n.sex,
    color: n.trim, hair: n.hair, blazer: n.blazer, trim: n.trim, skirt: n.skirt,
    // 名まえに合った かっこう（指定がなければ 性格のもの）
    style: n.style || A.style || "uniform",
    pants: n.pants !== undefined ? n.pants : W.pants,
    shoes: n.shoes !== undefined ? n.shoes : W.shoes,
    number: n.number, numColor: n.numColor, center: n.center, longHair: n.longHair,
    bald: n.bald, hat: n.hat,
    acc: n.acc, courage: n.courage, speed: n.speed, named: true,
    idle: n.idle.concat(A.idle.slice(0, 2)),
    scared: n.scared.concat(A.scared.slice(0, 1)),
    flee: n.flee,
  };
}

// 同じ組のなかで名まえがぶつかったら、別の人に取りかえる
function uniquify(members, reserved) {
  const seen = new Set();
  for (let i = 0; i < members.length; i++) {
    let m = members[i];
    let tries = 0;
    // 指名の人と同じ名まえになった一般の人も、取りかえる
    while ((seen.has(m.name) || (!m.named && reserved.has(m.name))) && tries < 60) {
      tries++;
      m = makePerson(m.arch, (m.seed || 1) + tries * 101 + 7);
      members[i] = m;
    }
    seen.add(m.name);
  }
  return members;
}

// グループの呼び名
const GROUP_LABEL = ["の一行", "たち", "のグループ", "御一行", "の仲間", "とその友達"];

export function buildRoster(count = 100) {
  const groups = [];
  const named = NAMED.map(namedToType);
  const namedNames = new Set(named.map((n) => n.name));

  for (let g = 0; g < count; g++) {
    const size = 2 + ((g * 3) % 4);              // 2〜5人
    const members = [];
    // 主となる性格を選び、そこに別の性格を混ぜる
    const mainA = ARCHETYPES[(g * 5) % ARCHETYPES.length];
    for (let i = 0; i < size; i++) {
      const a = i === 0 ? mainA : ARCHETYPES[(g * 7 + i * 3) % ARCHETYPES.length];
      members.push(makePerson(a.id, g * 13 + i * 5 + 1));
    }
    // 指名の8人を散らして入れる（8グループにひとりずつ、以降もときどき）
    // 指名の人が、どの回にも均等に出るようにする
    if (g % 3 === 1) {
      const n = named[((g - 1) / 3 | 0) % named.length];
      members[members.length - 1] = n;
    }
    // 同じ組に、同じ名まえの人がふたりいないようにする
    //  （名まえは「肩書き＋名」の組みあわせなので、たまたま重なることがある）
    uniquify(members, namedNames);
    groups.push({
      id: g,
      label: members[0].name + pick(GROUP_LABEL, g),
      members,
    });
  }
  // サッカー組は、たまに5人まとめて来る（本人たちが揃うと楽しい）
  const soccer = named.filter((n) => n.arch === "soccer");
  if (soccer.length >= 4) {
    groups[7] = { id: 7, label: "サッカー部の面々", members: soccer.slice(0, 5) };
    groups[47] = { id: 47, label: "サッカー部の面々（再訪）", members: soccer.slice(0, 4) };
  }
  // 湯上がりのおじさん3人組
  const oji = ["銭湯帰りのヨシダ", "体重100キロのコムスビ", "原チャのお坊さんクマキチ"]
    .map((nm) => named.find((n) => n.name === nm)).filter(Boolean);
  if (oji.length === 3) groups[31] = { id: 31, label: "湯上がりの三人組", members: oji };

  // 実況コンビ
  const kiyo = named.find((n) => n.name.indexOf("キヨ") >= 0);
  const hajimen = named.find((n) => n.name.indexOf("ハジメン") >= 0);
  if (kiyo && hajimen) {
    groups[19] = { id: 19, label: "コラボ企画の二人", members: [kiyo, hajimen, makePerson("photo", 501)] };
  }
  // 指名の人が ひとりも出そこねないよう、最後に確かめて入れなおす
  //  （組み合わせを決めうちした組があるので、はじき出される人が出る）
  const appear = new Set();
  for (const gr of groups) for (const m of gr.members) if (m.named) appear.add(m.name);
  let slot = 0;
  for (const n of named) {
    if (appear.has(n.name)) continue;
    // 指名の人がいない組をさがして、そこへ入れる
    while (slot < groups.length && groups[slot].members.some((m) => m.named)) slot++;
    if (slot >= groups.length) break;
    groups[slot].members[groups[slot].members.length - 1] = n;
    uniquify(groups[slot].members, namedNames);
    appear.add(n.name);
    slot++;
  }

  return groups;
}

// 同じ組が続けて来ないよう、順番を混ぜて配る
export class Roster {
  // seed をわたすと、来る順番が全員で同じになる（ともだちと遊ぶとき用）
  constructor(count = 100, seed = null) {
    this.groups = buildRoster(count);
    this.order = this.groups.map((g, i) => i);
    this.pick = seed == null ? Math.random : makeRng(seed ^ 0x5bf03635);
    this.shuffle();
    this.at = 0;
    this.round = 1;
  }
  shuffle() {
    for (let i = this.order.length - 1; i > 0; i--) {
      const j = Math.floor(this.pick() * (i + 1));
      const t = this.order[i]; this.order[i] = this.order[j]; this.order[j] = t;
    }
  }
  next() {
    if (this.at >= this.order.length) { this.shuffle(); this.at = 0; this.round++; }
    return this.groups[this.order[this.at++]];
  }
  get total() { return this.groups.length; }
}
